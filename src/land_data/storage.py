"""The only persistence contract used by pipeline and export code."""
from typing import Dict, List, Optional, Protocol, Sequence, Type, TypeVar

from .models import POI, ReviewDecision

T = TypeVar("T")


class Storage(Protocol):
    def put(self, item: object) -> None: ...

    def get(self, model: Type[T], item_id: str) -> Optional[T]: ...

    def all(self, model: Type[T]) -> List[T]: ...

    def pois_in_city(self, city: str) -> List[POI]: ...

    def recommendation_counts(self, poi_id: str) -> List[dict]: ...

    def purge_expired_raw(self, now: str) -> int: ...

    def prune_signals(self, mention_id: str, keep_ids: List[str]) -> None: ...

    def apply_review(self, items: List[object], decision: ReviewDecision,
                     related_decisions: Sequence[ReviewDecision] = ()) -> None: ...

    def review_history(self, target_type: str, target_id: str) -> List[ReviewDecision]: ...

    def get_extraction_cache(self, key: str, now: str) -> Optional[Dict]: ...

    def put_extraction_cache(self, key: str, result: Dict, expires_at: str) -> None: ...

    def source_runs(self) -> List[object]: ...

    def get_checkpoint(self, source: str, collection_key: str) -> Optional[object]: ...
